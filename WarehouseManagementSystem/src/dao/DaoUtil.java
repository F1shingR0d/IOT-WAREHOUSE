package dao;

import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.time.LocalDate;
import java.util.List;

/**
 * Small helpers shared by the DAO classes.
 */
final class DaoUtil {

    /** SQL fragment for a case-insensitive "contains" search on one column. */
    static final String LIKE = " LIKE ? ESCAPE '\\'";

    private DaoUtil() {
    }

    /**
     * Turns a search keyword into a LIKE pattern: "mouse" becomes "%MOUSE%".
     * The characters % and _ typed by the user are escaped so they are
     * searched literally.
     */
    static String likePattern(String keyword) {
        String text = keyword == null ? "" : keyword.trim().toUpperCase();
        text = text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_");
        return "%" + text + "%";
    }

    /** Returns the keyword as a number when the user typed an ID, otherwise null. */
    static Integer parseId(String keyword) {
        if (keyword == null) {
            return null;
        }
        try {
            return Integer.valueOf(keyword.trim());
        } catch (NumberFormatException e) {
            return null;
        }
    }

    /** Sets the values of a dynamically built query, in order. */
    static void bind(PreparedStatement ps, List<Object> params) throws SQLException {
        for (int i = 0; i < params.size(); i++) {
            Object value = params.get(i);
            if (value instanceof LocalDate) {
                ps.setDate(i + 1, Date.valueOf((LocalDate) value));
            } else {
                ps.setObject(i + 1, value);
            }
        }
    }

    /** Sets an optional text column: blank text is stored as NULL. */
    static void setText(PreparedStatement ps, int index, String value) throws SQLException {
        if (value == null || value.trim().isEmpty()) {
            ps.setNull(index, Types.VARCHAR);
        } else {
            ps.setString(index, value.trim());
        }
    }

    /** Sets an optional foreign key column: null is stored as NULL. */
    static void setInteger(PreparedStatement ps, int index, Integer value) throws SQLException {
        if (value == null) {
            ps.setNull(index, Types.INTEGER);
        } else {
            ps.setInt(index, value);
        }
    }

    /** Returns the IDENTITY value generated by the last INSERT of this statement. */
    static int generatedKey(PreparedStatement ps) throws SQLException {
        try (ResultSet keys = ps.getGeneratedKeys()) {
            return keys.next() ? keys.getInt(1) : 0;
        }
    }

    /** Runs a COUNT(*) style query that returns one number. */
    static int queryInt(Connection conn, String sql, Object... params) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            for (int i = 0; i < params.length; i++) {
                ps.setObject(i + 1, params[i]);
            }
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? rs.getInt(1) : 0;
            }
        }
    }

    /** Undoes a failed transaction without hiding the original error. */
    static void rollback(Connection conn, Exception original) {
        try {
            conn.rollback();
        } catch (SQLException rollbackError) {
            original.addSuppressed(rollbackError);
        }
    }

    static int insertAndGetId(PreparedStatement ps) throws SQLException {
        ps.executeUpdate();
        return generatedKey(ps);
    }

    static PreparedStatement prepareInsert(Connection conn, String sql) throws SQLException {
        return conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
    }
}
